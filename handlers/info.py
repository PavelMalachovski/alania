from aiogram import F, Router
from aiogram.types import CallbackQuery

from keyboards.inline import channel_kb, game_kb

router = Router()

GAME_TEXT = (
    "<b>♡ Психологическая игра для пар VECHNOST</b>\n\n"
    "Встречаться 2 года или прожить в браке 8 лет, чтобы вдруг узнать, что у вас "
    "принципиально разные ценности — безумно больно.\n\n"
    "Мы боимся задавать «неудобные» вопросы в начале отношений, надеясь, что всё "
    "сложится само.\n\n"
    "VECHNOST создана для того, чтобы убрать этот страх и безопасно узнать партнёра "
    "уже с самого начала общения. Это глубокий психологический инструмент и тренажёр "
    "коммуникации, основанный на:\n"
    "✦ теории привязанности и поведенческих сценариях\n"
    "✦ фундаментальной психологии отношений\n"
    "✦ практиках глубинной работы с десятками пар\n\n"
    "<b>Что внутри:</b> 300+ терапевтических вопросов и заданий, разбитых на 4 уровня. "
    "Они показывают истинное мышление человека и помогают убрать иллюзии ещё на старте — "
    "увидеть человека настоящим, без масок и фантазий, и сформировать прочную связь "
    "с самого начала общения."
)

CHANNEL_TEXT = (
    "<b>☾ Бесплатный Telegram-канал</b>\n\n"
    "В своём канале я рассказываю про психологию и не только — делюсь полезными "
    "материалами, подкастами и практиками. Они помогут тебе гармонизировать "
    "состояние и найти ответы на вопросы даже раньше, чем они у тебя возникнут ✦"
)


@router.callback_query(F.data == "game")
async def cb_game(callback: CallbackQuery) -> None:
    await callback.message.edit_text(GAME_TEXT, reply_markup=game_kb())


@router.callback_query(F.data == "channel")
async def cb_channel(callback: CallbackQuery) -> None:
    await callback.message.edit_text(CHANNEL_TEXT, reply_markup=channel_kb())
